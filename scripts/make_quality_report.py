"""Generate Cuttle conversion matrix and quality report (P5-06).

Per TRD task card P5-06:
- Generates docs/quality.md from registry edges and format specifications.
- Details each conversion pair, its quality label, adapter/tools, and known limits.
"""

from __future__ import annotations

from pathlib import Path

from cuttle.engine.registry import load_registry

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DOC = PROJECT_ROOT / "docs" / "quality.md"

LIMITS_BY_ADAPTER: dict[str, str] = {
    "ffmpeg": (
        "Video transcode is lossy (CPU-optimized h264/vp9). Audio to WAV is lossless PCM. "
        "Animation (GIF) palette quantizes to 256 colors."
    ),
    "image": (
        "Lossless across PNG, TIFF, BMP. Formats without alpha (JPG, BMP) flatten transparency "
        "onto white background. EXIF orientation is preserved."
    ),
    "pandoc": (
        "Converts document structure and standard formatting. Complex Office macros, equations, "
        "and embedded vector graphics may be simplified."
    ),
    "libreoffice": (
        "Exact visual layout fidelity. If host lacks proprietary source fonts, automatic font "
        "substitution warning is emitted."
    ),
    "pdf2docx": (
        "Best effort layout reconstruction. Tables, multi-column text, and complex vector headers "
        "may need touch-ups. Requires OCR for scanned image-only PDFs."
    ),
    "ocr": (
        "Text extracted from bitmap scans via Tesseract or OCRmyPDF. Output accuracy depends on "
        "scan DPI, contrast, and skew."
    ),
    "dwg": (
        "Best effort CAD vector export. Custom SHX fonts, 3D solids, and proprietary proxy objects "
        "are converted to standard 2D vector paths."
    ),
    "image_pdf": (
        "Direct bitmap encapsulation into PDF pages or high-resolution page rasterization. "
        "Original image pixel resolution is preserved."
    ),
}


def generate_quality_report() -> str:
    """Build markdown quality report string from the active registry."""
    reg = load_registry()
    lines: list[str] = [
        "# Cuttle Conversion Quality Report",
        "",
        "Cuttle is built on a simple promise: "
        "**honest offline conversion with zero file uploads**.",
        "Not all file conversions are equal. This report documents every supported "
        "conversion pair, its exact quality level, and known technical boundaries.",
        "",
        "## Quality Levels",
        "",
        "- **Lossless**: Bit-perfect or mathematically complete data preservation.",
        "- **Lossy**: Audio/video recompression or image quantization within perceptual limits.",
        "- **Best Effort**: Complex document, CAD, or OCR layout reconstruction where structural "
        "or styling shifts may occur.",
        "",
        "## Supported Conversions Matrix",
        "",
        "| Source | Target | Adapter | Quality | Cost | Notes & Known Limits |",
        "|:-------|:-------|:--------|:--------|:----:|:---------------------|",
    ]

    sorted_edges = sorted(reg.edges, key=lambda e: (e.src, e.dst))
    for edge in sorted_edges:
        src_def = reg.get_format(edge.src)
        dst_def = reg.get_format(edge.dst)
        src_label = src_def.id.upper() if src_def else edge.src.upper()
        dst_label = dst_def.id.upper() if dst_def else edge.dst.upper()

        limits = LIMITS_BY_ADAPTER.get(edge.adapter, "Standard format conversion.")
        if edge.src == "pdf" and edge.dst == "docx":
            limits = "Tables and complex layouts may need touch ups. Scanned PDFs require OCR."
        elif edge.src in ("dwg", "dxf"):
            limits = "CAD drawing conversion is best-effort. Requires LibreDWG or ODA add-on."

        row = (
            f"| `{src_label}` | `{dst_label}` | `{edge.adapter}` | "
            f"**{edge.quality.value.replace('_', ' ').capitalize()}** | {edge.cost}/10 | {limits} |"
        )
        lines.append(row)

    lines.extend(
        [
            "",
            "## Offline & Privacy Guarantees",
            "",
            "- **Zero Network Activity**: Cuttle's conversion engine has zero network "
            "permissions. Files never leave your local machine.",
            "- **Safe File Operations**: Cuttle never overwrites source files, writes to temporary "
            "`.cuttle-part` files during processing, and atomically replaces only on validation "
            "success.",
            "- **Clean Subprocess Isolation**: External engine processes run inside Windows Job "
            "Objects and automatically terminate on cancel or exit.",
            "",
            "---",
            "*Report automatically generated by `scripts/make_quality_report.py`.*",
            "",
        ]
    )

    return "\n".join(lines)


def main() -> None:
    """Generate and write docs/quality.md."""
    content = generate_quality_report()
    OUTPUT_DOC.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_DOC.write_text(content, encoding="utf-8")
    print(f"Quality report generated successfully at {OUTPUT_DOC}")


if __name__ == "__main__":
    main()
